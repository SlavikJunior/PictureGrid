package com.example.picturegrid.feature.gallery.api.domain

/**
 * Причина, по которой список не удалось получить из сети.
 *
 * Тип принадлежит домену и не ссылается на сетевой слой: домен описывает,
 * что произошло, а не каким транспортом это получено (INV-04, INV-06).
 * Текст для пользователя выбирается в UI по этому значению (INV-14).
 */
public enum class NetworkFailure {
    /** Ввод-вывод: соединение не установлено или оборвалось. */
    IO,

    /** Сервер не ответил за отведённое время. */
    TIMEOUT,

    /** Ответ пришёл пустым. */
    EMPTY_BODY,

    /** Сервер ответил кодом вне диапазона успеха. */
    HTTP,

    /** Тело ответа превысило допустимый объём. */
    TOO_LARGE,
}
