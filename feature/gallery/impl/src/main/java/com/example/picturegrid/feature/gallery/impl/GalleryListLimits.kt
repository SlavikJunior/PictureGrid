package com.example.picturegrid.feature.gallery.impl

import com.example.picturegrid.core.network.NetworkLimits

/**
 * Ограничения формата списка URL.
 *
 * Ограничения применяются на границе разбора и хранения: список не может
 * заставить приложение выделить неограниченный объём памяти или инициировать
 * бесконечное число запросов.
 */
object GalleryListLimits {

    /**
     * Максимальный объём текста списка.
     *
     * Совпадает с транспортным лимитом [NetworkLimits.MAX_TEXT_BYTES]:
     * файл списка не может быть больше ответа, из которого он получен.
     */
    const val MAX_TEXT_BYTES: Long = NetworkLimits.MAX_TEXT_BYTES

    /**
     * Максимальное число символов в разбираемом тексте: 1 048 576.
     *
     * Соответствует [MAX_TEXT_BYTES] для однобайтовой кодировки: текст,
     * полученный из сети или прочитанный из файла, не может быть длиннее
     * транспортного лимита.
     */
    const val MAX_TEXT_CHARS: Int = 1_048_576

    /**
     * Максимальное число элементов в списке: 5 000.
     *
     * Реальный список содержит десятки строк; ограничение защищает грид от
     * тысяч ячеек и столько же исходящих запросов за превью.
     */
    const val MAX_ITEMS: Int = 5_000

    /**
     * Максимальная длина одной строки списка: 4 096 символов.
     *
     * Заведомо больше длины любого легитимного URL, включая подписанные
     * ссылки CDN, но ограничивает память, приходящуюся на одну строку.
     */
    const val MAX_LINE_LENGTH: Int = 4_096
}
