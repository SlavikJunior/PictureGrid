package com.example.picturegrid.core.network

/**
 * Транспортные лимиты объёма данных.
 *
 * Ограничения заданы на уровне HTTP-клиента, чтобы тело ответа никогда не
 * читалось в память целиком: при превышении лимита запрос завершается
 * контролируемой ошибкой [NetworkError.TooLarge].
 *
 * Значения выбраны с запасом относительно ожидаемых данных PictureGrid:
 * список URL — текстовый файл, оригинал изображения — двоичный файл.
 */
object NetworkLimits {

    /**
     * Максимальный объём текстового ответа: 1 МиБ.
     *
     * Соответствует примерно 20 000 ссылок длиной около 50 символов и
     * многократно превышает реальный размер списка, поэтому обычное
     * использование не ограничивается, а pathological-список отсекается.
     */
    const val MAX_TEXT_BYTES: Long = 1L * 1024 * 1024

    /**
     * Максимальный объём бинарного ответа: 25 МиБ.
     *
     * Типичная фотография в высоком разрешении занимает 5–10 МиБ, поэтому
     * лимит не мешает обычным изображениям, но ограничивает объём,
     * который приложение держит в памяти при загрузке оригинала.
     */
    const val MAX_BINARY_BYTES: Long = 25L * 1024 * 1024
}
