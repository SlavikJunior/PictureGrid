package com.example.picturegrid.core.images

/**
 * Ограничения на принимаемое изображение.
 *
 * Значения подобраны так, чтобы обычные фотографии проходили без
 * ограничений, а заведомо недопустимые размеры отсекались до выделения
 * памяти под bitmap.
 */
object ImageLimits {

    /**
     * Максимальная сторона изображения в пикселях: 12 000.
     *
     * Значение с запасом покрывает фотографии современных камер
     * (например, 8064×6048 у камеры 48 Мп) и отсекает изображения
     * с синтетически недопустимыми габаритами.
     */
    const val MAX_DIMENSION: Int = 12_000

    /**
     * Максимальное число пикселей изображения: 60 млн (60 Мп).
     *
     * Соответствует фотографии примерно 9000×6600; изображения большего
     * размера не относятся к обычным пользовательским и отклоняются.
     */
    const val MAX_PIXELS: Long = 60_000_000L

    /**
     * Максимальное число пикселей уменьшенной копии, которая используется
     * для подтверждения декодируемости: 1 млн (1 Мп, около 4 МиБ памяти).
     */
    const val SAMPLE_MAX_PIXELS: Long = 1_000_000L
}
