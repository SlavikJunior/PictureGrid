package com.example.picturegrid.core.images

/**
 * Результат проверки содержимого, полученного по URL изображения.
 */
enum class ImageContent {

    /** Пригодное изображение допустимых размеров. */
    VALID,

    /** Данные не являются изображением или не декодируются. */
    NOT_IMAGE,

    /** Изображение корректно, но его размеры превышают допустимые. */
    TOO_LARGE,
}

/**
 * Проверяет содержимое ответа до сохранения оригинала.
 *
 * Вынесено в отдельную границу, чтобы проверка не зависела от Android API:
 * тесты подставляют собственную реализацию, а приложение использует
 * [ImageInspector], который читает размеры из заголовка файла, не выделяя
 * память под полноразмерный bitmap.
 */
fun interface ImageContentChecker {
    fun check(bytes: ByteArray): ImageContent
}
